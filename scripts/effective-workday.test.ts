import assert from 'node:assert/strict'
import {calculateEffectiveWorkday} from '../src/utils/wageDay.ts'

const base={rawLateMinutes:0,rawEarlyLeaveMinutes:293,rawPostShiftMinutes:0,dayUnits:.5,hasOverride:true,scheduledStartAt:new Date('2026-08-07T08:00:00+07:00'),scheduledEndAt:new Date('2026-08-07T17:00:00+07:00'),clockInAt:new Date('2026-08-07T07:37:00+07:00'),clockOutAt:new Date('2026-08-07T12:07:00+07:00'),halfDayMinutes:240,graceMinutes:5,halfMorningEndAt:new Date('2026-08-07T12:00:00+07:00'),halfAfternoonStartAt:new Date('2026-08-07T13:00:00+07:00')}
const morning=calculateEffectiveWorkday({...base,overrideMode:'half_morning'})
assert.equal(morning.earlyLeaveMinutes,0)
assert.equal(morning.postShiftMinutes,7)
assert.equal(morning.lateMinutes,0)
const early=calculateEffectiveWorkday({...base,overrideMode:'half_morning',clockOutAt:new Date('2026-08-07T11:45:00+07:00')})
assert.equal(early.earlyLeaveMinutes,15)
const afternoon=calculateEffectiveWorkday({...base,overrideMode:'half_afternoon',clockInAt:new Date('2026-08-07T13:15:00+07:00'),clockOutAt:new Date('2026-08-07T17:05:00+07:00')})
assert.equal(afternoon.lateMinutes,10)
assert.equal(afternoon.postShiftMinutes,5)
const custom=calculateEffectiveWorkday({...base,graceMinutes:0,overrideMode:'custom_period',customStartAt:new Date('2026-08-07T14:00:00+07:00'),customEndAt:new Date('2026-08-07T18:00:00+07:00'),clockInAt:new Date('2026-08-07T14:05:00+07:00'),clockOutAt:new Date('2026-08-07T17:50:00+07:00')})
assert.equal(custom.lateMinutes,5);assert.equal(custom.earlyLeaveMinutes,10)
const wageOnly=calculateEffectiveWorkday({...base,overrideMode:'wage_only'})
assert.equal(wageOnly.earlyLeaveMinutes,293)
const systemMorning=calculateEffectiveWorkday({...base,hasOverride:false,overrideMode:null})
assert.equal(systemMorning.mode,'half_morning')
assert.equal(systemMorning.earlyLeaveMinutes,0)
assert.equal(systemMorning.postShiftMinutes,7)
const systemAfternoon=calculateEffectiveWorkday({...base,hasOverride:false,overrideMode:null,clockInAt:new Date('2026-08-07T14:00:00+07:00'),clockOutAt:new Date('2026-08-07T18:00:00+07:00')})
assert.equal(systemAfternoon.mode,'half_afternoon')
assert.equal(systemAfternoon.lateMinutes,55)
assert.equal(systemAfternoon.earlyLeaveMinutes,0)
assert.equal(systemAfternoon.postShiftMinutes,60)
const ambiguous=calculateEffectiveWorkday({...base,hasOverride:false,overrideMode:null,clockInAt:new Date('2026-08-07T08:43:00+07:00'),clockOutAt:new Date('2026-08-07T17:01:00+07:00')})
assert.equal(ambiguous.resolved,false)
assert.match(ambiguous.reason??'',/กรุณาเลือกช่วงครึ่งวัน/)
assert.equal(ambiguous.earlyLeaveMinutes,293)
const fullDay=calculateEffectiveWorkday({...base,dayUnits:1,hasOverride:false,overrideMode:null,clockInAt:new Date('2026-08-07T08:30:00+07:00'),clockOutAt:new Date('2026-08-07T18:00:00+07:00')})
assert.equal(fullDay.lateMinutes,25)
assert.equal(fullDay.earlyLeaveMinutes,0)
assert.equal(fullDay.postShiftMinutes,60)
const missingSchedule=calculateEffectiveWorkday({...base,scheduledStartAt:null,scheduledEndAt:null})
assert.equal(missingSchedule.resolved,false)
assert.match(missingSchedule.reason??'',/ไม่พบกะ/)
console.log('effective workday regression passed')
