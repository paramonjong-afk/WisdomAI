create or replace function public.record_system_work_cost_v2(
  target_run uuid,target_worker text,target_token_input integer,target_token_output integer,
  target_estimated_cost numeric default 0,target_actual_cost numeric default 0,target_cache_hit boolean default false
) returns boolean language plpgsql security definer set search_path=public as $$
declare r public.system_worker_runs; i public.system_work_items; inserted_count integer;
begin
  select * into r from public.system_worker_runs where id=target_run and worker_id=target_worker;
  if r.id is null then return false; end if;
  select * into i from public.system_work_items where work_key=r.work_key;
  insert into public.system_work_cost_events(work_key,run_id,company_id,model_tier,model_name,token_input,token_output,estimated_cost_usd,actual_cost_usd,cache_hit,escalation_level)
  values(i.work_key,r.id,i.company_id,i.model_tier,i.model_name,greatest(coalesce(target_token_input,0),0),greatest(coalesce(target_token_output,0),0),greatest(coalesce(target_estimated_cost,0),0),greatest(coalesce(target_actual_cost,0),0),coalesce(target_cache_hit,false),i.escalation_level)
  on conflict (run_id) where run_id is not null do nothing;
  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then return true; end if;
  update public.system_worker_runs set token_input=greatest(coalesce(target_token_input,0),0),token_output=greatest(coalesce(target_token_output,0),0),
    estimated_cost_usd=greatest(coalesce(target_estimated_cost,0),0),actual_cost_usd=greatest(coalesce(target_actual_cost,0),0),cache_hit=coalesce(target_cache_hit,false) where id=r.id;
  update public.system_work_items set token_input_total=token_input_total+greatest(coalesce(target_token_input,0),0),
    token_output_total=token_output_total+greatest(coalesce(target_token_output,0),0),estimated_cost_usd=estimated_cost_usd+greatest(coalesce(target_estimated_cost,0),0),
    actual_cost_usd=actual_cost_usd+greatest(coalesce(target_actual_cost,0),0),cache_hit=coalesce(target_cache_hit,false),updated_at=now() where work_key=i.work_key;
  return true;
end $$;
revoke all on function public.record_system_work_cost_v2(uuid,text,integer,integer,numeric,numeric,boolean) from public,anon,authenticated;
grant execute on function public.record_system_work_cost_v2(uuid,text,integer,integer,numeric,numeric,boolean) to service_role;

