  token_budget_input between 1000 and 1000000 and token_budget_output between 500 and 250000
  and token_soft_limit_percent between 50 and 95 and escalation_level between 0 and 3
);

alter table public.system_worker_runs
  add column if not exists model_tier text,
  add column if not exists model_name text,
  add column if not exists token_budget_input integer,
  add column if not exists token_budget_output integer,
  add column if not exists prompt_version text,
