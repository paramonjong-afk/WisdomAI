alter table public.system_work_items drop constraint if exists system_work_items_qa_tier_check;
alter table public.system_work_items add constraint system_work_items_qa_tier_check check (qa_tier in ('automated','standard','independent','human'));
alter table public.system_work_items drop constraint if exists system_work_items_token_budget_check;
