create table if not exists public.system_model_policies (
  id bigint generated by default as identity primary key,
  company_id uuid references public.companies(id) on delete cascade,
  category text,
  risk text,
  model_tier text not null check(model_tier in ('economy','balanced','reasoning')),
  model_name text,
  token_budget_input integer not null,
  token_budget_output integer not null,
  token_soft_limit_percent integer not null default 80 check(token_soft_limit_percent between 50 and 95),
  qa_tier text not null check(qa_tier in ('automated','standard','independent','human')),
  max_concurrency integer not null default 1 check(max_concurrency between 1 and 20),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists system_model_policies_scope_idx on public.system_model_policies(
  coalesce(company_id,'00000000-0000-0000-0000-000000000000'::uuid),coalesce(category,'*'),coalesce(risk,'*')
);

create table if not exists public.system_work_result_cache (
  cache_key text primary key,
  work_key text not null references public.system_work_items(work_key) on delete cascade,
  requirement_version integer not null,
  source_sha text not null,
  prompt_version text not null,
  output_schema_version text not null,
  dependency_hash text not null,
  result jsonb not null,
  evidence_refs jsonb not null default '[]'::jsonb,
  valid_until timestamptz,
  created_at timestamptz not null default now(),
  last_hit_at timestamptz,
  hit_count integer not null default 0
);

create table if not exists public.system_work_cost_events (
  id bigint generated by default as identity primary key,
  work_key text not null references public.system_work_items(work_key) on delete cascade,
  run_id uuid references public.system_worker_runs(id) on delete set null,
  company_id uuid references public.companies(id) on delete cascade,
  model_tier text not null,
  model_name text,
  token_input integer not null default 0,
  token_output integer not null default 0,
  estimated_cost_usd numeric(14,6) not null default 0,
  actual_cost_usd numeric(14,6) not null default 0,
  cache_hit boolean not null default false,
  escalation_level smallint not null default 0,
  recorded_at timestamptz not null default now()
);
create index if not exists system_work_cost_events_work_idx on public.system_work_cost_events(work_key,recorded_at desc);
create unique index if not exists system_work_cost_events_run_idx on public.system_work_cost_events(run_id) where run_id is not null;

create table if not exists public.system_work_resource_locks (
  resource_key text primary key,
  work_key text not null references public.system_work_items(work_key) on delete cascade,
  run_id uuid references public.system_worker_runs(id) on delete cascade,
  worker_id text not null,
  lease_expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

