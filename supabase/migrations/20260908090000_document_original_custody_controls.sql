create or replace function public.backfill_document_custody_metadata(target_limit integer default 500)
returns table(updated_count integer, exception_count integer)
language plpgsql security definer set search_path = public, pg_temp
as $$
declare row_item record; updated integer:=0; exceptions integer:=0; affected integer:=0; retain_date date;
begin
  if not public.is_platform_admin() then raise exception 'platform_admin_permission_required'; end if;
  for row_item in
    select attachment.*
    from public.line_attachments attachment
    where attachment.company_id is not null and (
      (attachment.retain_until is null and attachment.retention_class in ('financial','temporary','work_evidence'))
      or ((nullif(btrim(attachment.storage_path),'') is null or attachment.content_type is null or attachment.content_sha256 is null or attachment.blob_id is null)
        and not exists(select 1 from public.document_custody_exceptions exception_row
          where exception_row.company_id=attachment.company_id and exception_row.attachment_id=attachment.id and exception_row.status='open'))
    )
    order by attachment.created_at,attachment.id
    limit least(greatest(target_limit,1),5000)
  loop
    if row_item.retain_until is null and row_item.retention_class in ('financial','temporary','work_evidence') then
      retain_date := case
        when row_item.retention_class='financial' then (date_trunc('year',row_item.created_at) + interval '8 years - 1 day')::date
        else (row_item.created_at + interval '2 years')::date
      end;
      update public.line_attachments set retain_until=retain_date where id=row_item.id and retain_until is null;
      get diagnostics affected = row_count;
      updated:=updated+affected;
    end if;
    if nullif(btrim(row_item.storage_path),'') is null or row_item.content_type is null or row_item.content_sha256 is null or row_item.blob_id is null then
      insert into public.document_custody_exceptions(company_id,attachment_id,reason)
      values(row_item.company_id,row_item.id,'missing_integrity_metadata') on conflict do nothing;
      get diagnostics affected = row_count;
      exceptions:=exceptions+affected;
    end if;
  end loop;
  return query select updated,exceptions;
end $$;
revoke all on function public.backfill_document_custody_metadata(integer) from public, anon, authenticated;
grant execute on function public.backfill_document_custody_metadata(integer) to service_role;

