create or replace function public.is_document_operations(target_company_id uuid default public.current_company_id())
returns boolean
language sql stable security definer set search_path = public, pg_temp
as $$
  select public.is_platform_admin()
    or exists (
      select 1
      from public.company_members member
      where member.company_id = target_company_id
        and member.profile_id = auth.uid()
        and member.active
        and (member.ends_on is null or member.ends_on >= current_date)
        and member.company_role in ('company_admin','executive','manager','accounting_hr')
    );
$$;
revoke all on function public.is_document_operations(uuid) from public, anon;
grant execute on function public.is_document_operations(uuid) to authenticated;

create table if not exists public.document_original_recovery_grants (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  attachment_id uuid not null references public.line_attachments(id) on delete restrict,
  requested_by uuid not null references public.profiles(id) on delete restrict,
  approved_by uuid references public.profiles(id) on delete restrict,
  status text not null default 'pending' check (status in ('pending','approved','used','expired','rejected','revoked')),
  reason text not null check (length(btrim(reason)) between 5 and 500),
  storage_bucket text not null,
  storage_path text not null,
  content_sha256 text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  approved_at timestamptz,
  used_at timestamptz,
  check (expires_at <= coalesce(approved_at, created_at) + interval '15 minutes'),
  unique (company_id, attachment_id, requested_by, created_at)
);
create index if not exists document_original_recovery_grants_queue_idx
  on public.document_original_recovery_grants(company_id, status, expires_at);
create unique index if not exists document_original_recovery_one_open_per_attachment_idx
  on public.document_original_recovery_grants(company_id, attachment_id)
  where status in ('pending','approved');
alter table public.document_original_recovery_grants enable row level security;
drop policy if exists "Document operations read recovery grants" on public.document_original_recovery_grants;
create policy "Document operations read recovery grants"
  on public.document_original_recovery_grants for select to authenticated
  using (company_id = public.current_company_id() and public.is_document_operations(company_id));
revoke insert, update, delete on public.document_original_recovery_grants from anon, authenticated;

create table if not exists public.document_original_recovery_audit (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  grant_id uuid not null references public.document_original_recovery_grants(id) on delete restrict,
  event_key text not null,
  actor_id uuid references public.profiles(id) on delete set null,
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (grant_id, event_key)
);
create index if not exists document_original_recovery_audit_company_idx
  on public.document_original_recovery_audit(company_id, created_at desc);
alter table public.document_original_recovery_audit enable row level security;
create policy "Document operations read recovery audit"
  on public.document_original_recovery_audit for select to authenticated
  using (company_id = public.current_company_id() and public.is_document_operations(company_id));
revoke insert, update, delete on public.document_original_recovery_audit from anon, authenticated;

create or replace function public.request_document_original_recovery(target_attachment_id uuid, target_reason text)
returns public.document_original_recovery_grants
language plpgsql security definer set search_path = public, pg_temp
as $$
declare company uuid := public.current_company_id(); attachment public.line_attachments; result public.document_original_recovery_grants;
begin
  if company is null or not public.is_document_operations(company) then raise exception 'document_operations_permission_required'; end if;
  if nullif(btrim(target_reason),'') is null or length(btrim(target_reason)) not between 5 and 500 then raise exception 'recovery_reason_length_invalid'; end if;
  select * into attachment from public.line_attachments where id=target_attachment_id and company_id=company for update;
  if attachment.id is null then raise exception 'attachment_not_found'; end if;
  update public.document_original_recovery_grants grant_row
  set status='expired'
  where grant_row.company_id=company and grant_row.attachment_id=attachment.id
    and grant_row.status in ('pending','approved') and grant_row.expires_at<=now();
  insert into public.document_original_recovery_audit(company_id,grant_id,event_key,actor_id,event_data)
  select company,grant_row.id,'expired',auth.uid(),jsonb_build_object('expired_at',now())
  from public.document_original_recovery_grants grant_row
  where grant_row.company_id=company and grant_row.attachment_id=attachment.id and grant_row.status='expired'
  on conflict(grant_id,event_key) do nothing;
  select * into result from public.document_original_recovery_grants grant_row
  where grant_row.company_id=company and grant_row.attachment_id=attachment.id
    and grant_row.status in ('pending','approved') and grant_row.expires_at>now()
  order by grant_row.created_at desc limit 1;
  if result.id is not null then return result; end if;
  insert into public.document_original_recovery_grants(company_id,attachment_id,requested_by,reason,storage_bucket,storage_path,content_sha256,expires_at)
  values(company,attachment.id,auth.uid(),btrim(target_reason),attachment.storage_bucket,attachment.storage_path,attachment.content_sha256,now()+interval '15 minutes')
  returning * into result;
  insert into public.document_original_recovery_audit(company_id,grant_id,event_key,actor_id,event_data)
  values(company,result.id,'requested',auth.uid(),jsonb_build_object('attachment_id',attachment.id,'content_sha256',attachment.content_sha256));
  return result;
end $$;
revoke all on function public.request_document_original_recovery(uuid,text) from public, anon;
grant execute on function public.request_document_original_recovery(uuid,text) to authenticated;

create or replace function public.decide_document_original_recovery(target_grant_id uuid, target_decision text)
returns public.document_original_recovery_grants
language plpgsql security definer set search_path = public, pg_temp
as $$
declare company uuid := public.current_company_id(); result public.document_original_recovery_grants; next_status text;
begin
  if company is null or (not public.is_platform_admin() and not public.is_company_manager(company)) then raise exception 'admin_approval_required'; end if;
  if target_decision not in ('approved','rejected','revoked') then raise exception 'invalid_recovery_decision'; end if;
  select * into result from public.document_original_recovery_grants
  where id=target_grant_id and company_id=company and status=target_decision;
  if result.id is not null then return result; end if;
  update public.document_original_recovery_grants
  set status=target_decision, approved_by=case when target_decision='approved' then auth.uid() else approved_by end,
      approved_at=case when target_decision='approved' then now() else approved_at end,
      expires_at=case when target_decision='approved' then now()+interval '15 minutes' else expires_at end
  where id=target_grant_id and company_id=company
    and (
      (target_decision in ('approved','rejected') and status='pending' and expires_at>now())
      or (target_decision='revoked' and status in ('pending','approved'))
    )
  returning * into result;
  if result.id is null then raise exception 'recovery_grant_not_pending_or_expired'; end if;
  insert into public.document_original_recovery_audit(company_id,grant_id,event_key,actor_id,event_data)
  values(company,result.id,target_decision,auth.uid(),jsonb_build_object('expires_at',result.expires_at));
  return result;
end $$;
revoke all on function public.decide_document_original_recovery(uuid,text) from public, anon;
grant execute on function public.decide_document_original_recovery(uuid,text) to authenticated;

create or replace function public.consume_document_original_recovery(target_grant_id uuid)
returns table(storage_bucket text, storage_path text, content_sha256 text, expires_at timestamptz)
language plpgsql security definer set search_path = public, pg_temp
as $$
declare company uuid := public.current_company_id(); grant_row public.document_original_recovery_grants;
begin
  if company is null or not public.is_document_operations(company) then raise exception 'document_operations_permission_required'; end if;
  update public.document_original_recovery_grants grant_record
  set status='used', used_at=now()
  where grant_record.id=target_grant_id and grant_record.company_id=company
    and grant_record.status='approved' and grant_record.expires_at>now()
  returning * into grant_row;
  if grant_row.id is null then raise exception 'recovery_grant_not_approved_or_expired'; end if;
  insert into public.document_original_recovery_audit(company_id,grant_id,event_key,actor_id,event_data)
  values(company,grant_row.id,'consumed',auth.uid(),jsonb_build_object('used_at',now()));
  return query select grant_row.storage_bucket,grant_row.storage_path,grant_row.content_sha256,grant_row.expires_at;
end $$;
revoke all on function public.consume_document_original_recovery(uuid) from public, anon;
grant execute on function public.consume_document_original_recovery(uuid) to authenticated;

